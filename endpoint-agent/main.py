"""
SecureWatch Endpoint Agent CLI Entry Point.
Commands:
  python main.py --enroll --server-url https://soc.company.com --token <ENROLLMENT_TOKEN>
  python main.py --start
  python main.py --status
  python main.py --version
"""
from __future__ import annotations

import argparse
import asyncio
import os
import sys
try:
    import structlog
    log = structlog.get_logger(__name__)
except ImportError:
    import logging
    logging.basicConfig(level=logging.INFO)
    log = logging.getLogger("securewatch-agent")

from agent.config import AgentConfig, AGENT_VERSION
from agent.collectors.device_info import get_device_info


def parse_args():
    parser = argparse.ArgumentParser(
        description="SecureWatch Endpoint Security Agent",
        formatter_class=argparse.RawDescriptionHelpFormatter,
    )
    parser.add_argument(
        "--enroll", action="store_true", help="Enroll this device with the SecureWatch central server"
    )
    parser.add_argument("--server-url", type=str, help="URL of the SecureWatch server")
    parser.add_argument("--token", type=str, help="One-time enrollment token generated by administrator")
    parser.add_argument("--start", action="store_true", help="Start the endpoint security agent service")
    parser.add_argument("--status", action="store_true", help="Check local agent enrollment and connection status")
    parser.add_argument("--version", action="version", version=f"SecureWatch Agent v{AGENT_VERSION}")

    return parser.parse_args()


async def do_enroll(server_url: str, token: str):
    print("=" * 60)
    print(" SecureWatch Endpoint Enrollment")
    print("=" * 60)

    if not server_url:
        print("Error: --server-url is required for enrollment")
        sys.exit(1)
    if not token:
        print("Error: --token is required for enrollment")
        sys.exit(1)

    server_url = server_url.rstrip("/")
    print(f"[*] Discovering system telemetry...")
    info = get_device_info(agent_version=AGENT_VERSION)
    print(f"    - Hostname: {info['hostname']}")
    print(f"    - OS:       {info['os_name']} ({info['os_arch']})")
    print(f"    - IP:       {info['private_ip']}")

    enroll_payload = {
        "enrollment_token": token,
        "hostname": info["hostname"],
        "os_name": info["os_name"],
        "os_version": info["os_version"],
        "os_arch": info["os_arch"],
        "private_ip": info["private_ip"],
        "mac_address": info["mac_address"],
        "agent_version": AGENT_VERSION,
        "system_metadata": info["system_metadata"],
    }

    print(f"[*] Connecting to {server_url}/api/v1/devices/enroll ...")
    temp_config = AgentConfig(
        server_url=server_url,
        device_id="",
        device_secret="",
        access_token="",
        enrollment_token=token,
    )

    from agent.transport.api_client import SecureWatchClient

    async with SecureWatchClient(temp_config) as client:
        try:
            resp = await client.enroll(enroll_payload)
            if not resp or "device_token" not in resp:
                print("[!] Enrollment rejected by server.")
                sys.exit(1)

            device_id = str(resp["device_id"])
            device_token = resp["device_token"]
            approved = resp.get("approved", True)

            print("[+] Enrollment SUCCESSFUL!")
            print(f"    - Device ID: {device_id}")
            print(f"    - Status:    {resp.get('status', 'online')}")
            if not approved:
                print("    - Notice: Device requires administrator approval before active telemetry.")

            # Save persistent configuration
            saved_config = AgentConfig(
                server_url=server_url,
                device_id=device_id,
                device_secret=device_token,
                access_token=device_token,
                enrollment_token="",
                heartbeat_interval=resp.get("heartbeat_interval", 60),
            )
            saved_config.save()
            from agent.config import get_config_path
            print(f"[+] Saved credentials to {get_config_path()}")
            print("[*] You can now start the agent using: python main.py --start")

        except Exception as e:
            print(f"[!] Enrollment failed: {e}")
            sys.exit(1)


async def do_start():
    config = AgentConfig.load()
    if not config or not config.device_id or not config.access_token:
        print("[!] Agent is not enrolled yet. Please run:")
        print("    python main.py --enroll --server-url <URL> --token <TOKEN>")
        sys.exit(1)

    print("=" * 60)
    print(f" SecureWatch Agent v{AGENT_VERSION} – Active")
    print(f" Device ID: {config.device_id}")
    print(f" Server:    {config.server_url}")
    print("=" * 60)

    from agent.agent import SecureWatchAgent
    agent = SecureWatchAgent(config)
    try:
        await agent.start()
        while True:
            await asyncio.sleep(1)
    except (KeyboardInterrupt, SystemExit):
        await agent.stop()


def do_status():
    config = AgentConfig.load()
    if not config or not config.device_id:
        print("[*] Status: UNENROLLED")
        print("    Run `python main.py --enroll` to register this endpoint.")
        return

    print("=" * 60)
    print(" SecureWatch Agent Status")
    print("=" * 60)
    print(f"Agent Version:   {AGENT_VERSION}")
    print(f"Device ID:       {config.device_id}")
    print(f"Server URL:      {config.server_url}")
    print(f"Heartbeat:       Every {config.heartbeat_interval}s")
    print(f"Status:          CONFIGURED & READY")


def main():
    args = parse_args()
    if args.enroll:
        asyncio.run(do_enroll(args.server_url, args.token))
    elif args.start:
        asyncio.run(do_start())
    elif args.status:
        do_status()
    else:
        do_status()


if __name__ == "__main__":
    main()
